import type { Router } from './router'
import type { BrowserService } from '../main/services/browser/BrowserService'

/** Binds the browser:* contract channels (the desktop window's browser) to BrowserService. */
export function registerBrowserIpc(router: Router, browser: BrowserService): void {
  router.register('browser:extensions', () => browser.extensions.list())
  router.register('browser:extensions:install', (req) => browser.extensions.install(req))
  router.register('browser:extensions:profiles', () => browser.extensions.profiles())
  router.register('browser:extensions:update', ({ id, enabled }) => browser.extensions.setEnabled(id, enabled))
  router.register('browser:extensions:remove', ({ id }) => browser.extensions.remove(id))
  router.register('browser:extensions:checkUpdates', () => browser.extensions.checkUpdates())
  router.register('browser:extensions:popup', ({ id, anchor }) => browser.extensions.popup(id, anchor))
  router.register('browser:auth', ({ id, username, password }) => browser.answerAuth(id, username, password))
  router.register('browser:proceed', ({ id }) => browser.proceed(id))
  router.register('browser:dismissDrm', ({ id }) => browser.dismissDrm(id))
  router.register('browser:pickDownloadDir', () => browser.pickDownloadDir())
  router.register('browser:state', () => browser.state())
  router.register('browser:open', ({ url, background, private: priv }) => browser.open({ url, background, private: priv }))
  router.register('browser:close', ({ id }) => browser.close(id))
  router.register('browser:activate', ({ id }) => browser.activate(id))
  router.register('browser:navigate', ({ id, input }) => browser.navigate(id, input))
  router.register('browser:capture', ({ id, width }) => browser.capture(id, width))
  router.register('browser:input', ({ id, ...input }) => browser.input(id, input))
  router.register('browser:go', ({ id, action }) => browser.go(id, action))
  router.register('browser:update', ({ id, ...patch }) => browser.update(id, patch))
  router.register('browser:move', ({ id, index, groupId }) => browser.move(id, index, groupId))
  router.register('browser:duplicate', ({ id }) => browser.duplicate(id))
  router.register('browser:reopen', () => browser.reopen())
  router.register('browser:zoom', ({ id, zoom }) => browser.zoom(id, zoom))
  router.register('browser:find', ({ id, text, forward, next }) => browser.find(id, text, forward, next))
  router.register('browser:findStop', ({ id }) => browser.findStop(id))
  router.register('browser:tool', ({ id, tool }) => browser.tool(id, tool))
  router.register('browser:view', ({ bounds, focused, panes }) => browser.setView(bounds, focused, panes))
  router.register('browser:freeze', () => browser.freeze())
  router.register('browser:unfreeze', () => browser.unfreeze())
  router.register('browser:suggest', ({ text }) => browser.suggest(text))
  router.register('browser:history', ({ query, limit }) => browser.historyEntries(query, limit))
  router.register('browser:clearHistory', () => browser.clearHistory())
  router.register('browser:download', ({ id, action }) => browser.download(id, action))
  router.register('browser:permission', ({ id, allow, remember }) => browser.permission(id, allow, remember))
  router.register('browser:settings', () => browser.settings())
  router.register('browser:configure', (patch) => browser.configure(patch))
  router.register('browser:ui', (ui) => browser.setUi(ui))
  router.register('browser:searchSuggest', ({ text }) => browser.searchSuggestions(text))
  router.register('browser:historyList', (opts) => browser.historyList(opts))
  router.register('browser:historyDelete', (what) => browser.deleteHistory(what))
  router.register('browser:bookmarks', () => browser.bookmarkTree())
  router.register('browser:bookmarkAdd', (req) => browser.addBookmark(req))
  router.register('browser:bookmarkUpdate', ({ id, ...patch }) => browser.updateBookmark(id, patch))
  router.register('browser:bookmarkMove', ({ id, parentId, index }) => browser.moveBookmark(id, parentId, index))
  router.register('browser:bookmarkRemove', ({ ids }) => browser.removeBookmarks(ids))
  router.register('browser:bookmarksExport', () => browser.exportBookmarks())
  router.register('browser:bookmarksImport', ({ html }) => browser.importBookmarksHtml(html))
  router.register('browser:importSources', () => browser.importSources())
  router.register('browser:import', (req) => browser.importFrom(req))
  router.register('browser:restoreSession', ({ restore }) => browser.restoreSession(restore))
  router.register('browser:group', ({ ids, ...opts }) => browser.group(ids, opts))
  router.register('browser:groupUpdate', ({ id, ...patch }) => browser.updateGroup(id, patch))
  router.register('browser:ungroup', ({ id }) => browser.ungroup(id))
  router.register('browser:groupClose', ({ id }) => browser.closeGroup(id))
  router.register('browser:split', ({ id, with: other, vertical }) => browser.split(id, other, vertical))
  router.register('browser:splitUpdate', ({ id, ...patch }) => browser.updateSplit(id, patch))
  router.register('browser:unsplit', ({ id }) => browser.unsplit(id))
}
